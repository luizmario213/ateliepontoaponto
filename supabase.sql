-- Cria ou edita um pedido inteiro numa única operação (tudo ou nada).
-- Se o mesmo pedido for enviado duas vezes (toque duplo, internet ruim),
-- não duplica: a segunda chamada só regrava os mesmos dados.
create or replace function public.salvar_pedido(p jsonb)
returns jsonb language plpgsql security invoker set search_path = ''
as $$
declare
  v_id      uuid := (p->>'id')::uuid;
  v_cli     uuid := nullif(p->>'cliente_id','')::uuid;
  v_novo    boolean;
  v_total   numeric(10,2);
  v_pago    numeric(10,2);
  v_pag     jsonb := p->'pagamento';
  v_ped     public.pedidos;
  v_item    jsonb;
  v_ordem   integer := 0;
begin
  if not public.eh_membro() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  if v_id is null then raise exception 'Pedido sem identificador.'; end if;
  if jsonb_typeof(p->'itens') <> 'array' or jsonb_array_length(p->'itens') = 0 then
    raise exception 'Adicione pelo menos um serviço.';
  end if;
  if nullif(p->>'entregar_em','') is null then raise exception 'Informe a data de entrega.'; end if;

  -- cliente nova cadastrada junto com o pedido
  if p ? 'cliente_nova' and jsonb_typeof(p->'cliente_nova') = 'object' then
    v_cli := (p->'cliente_nova'->>'id')::uuid;
    insert into public.clientes (id, nome, fone)
    values (v_cli, btrim(p->'cliente_nova'->>'nome'), btrim(coalesce(p->'cliente_nova'->>'fone','')))
    on conflict (id) do nothing;
  end if;
  if v_cli is null then raise exception 'Escolha a cliente.'; end if;

  select not exists (select 1 from public.pedidos where id = v_id) into v_novo;

  if v_novo then
    insert into public.pedidos (id, cliente_id, recebido_em, entregar_em, detalhes)
    values (v_id, v_cli,
            coalesce(nullif(p->>'recebido_em','')::date, public.hoje()),
            (p->>'entregar_em')::date,
            btrim(coalesce(p->>'detalhes','')));
  else
    perform 1 from public.pedidos where id = v_id for update;
    update public.pedidos set
      cliente_id  = v_cli,
      recebido_em = coalesce(nullif(p->>'recebido_em','')::date, recebido_em),
      entregar_em = (p->>'entregar_em')::date,
      detalhes    = btrim(coalesce(p->>'detalhes',''))
    where id = v_id;
    delete from public.pedido_itens where pedido_id = v_id;
  end if;

  for v_item in select * from jsonb_array_elements(p->'itens') loop
    v_ordem := v_ordem + 1;
    insert into public.pedido_itens (pedido_id, servico_id, nome, qtd, preco, custo, avulso, ordem)
    values (v_id,
            nullif(v_item->>'servico_id','')::uuid,
            btrim(v_item->>'nome'),
            (v_item->>'qtd')::integer,
            round((v_item->>'preco')::numeric, 2),
            round(coalesce((v_item->>'custo')::numeric, 0), 2),
            coalesce((v_item->>'avulso')::boolean, false),
            v_ordem);
  end loop;

  select coalesce(sum(qtd * preco), 0) into v_total from public.pedido_itens where pedido_id = v_id;

  -- sinal pago no balcão (só na criação)
  if v_novo and v_pag is not null and jsonb_typeof(v_pag) = 'object'
     and coalesce((v_pag->>'valor')::numeric, 0) > 0 then
    if (v_pag->>'valor')::numeric > v_total then
      raise exception 'O valor pago (R$ %) é maior que o total do pedido (R$ %).', v_pag->>'valor', v_total;
    end if;
    insert into public.pagamentos (id, pedido_id, pago_em, valor, forma, taxa)
    values (coalesce(nullif(v_pag->>'id','')::uuid, gen_random_uuid()), v_id,
            coalesce(nullif(v_pag->>'pago_em','')::date, public.hoje()),
            round((v_pag->>'valor')::numeric, 2),
            coalesce(nullif(v_pag->>'forma',''), 'Pix'),
            round(coalesce((v_pag->>'taxa')::numeric, 0), 2))
    on conflict (id) do nothing;
  end if;

  select coalesce(sum(valor), 0) into v_pago from public.pagamentos where pedido_id = v_id;
  if v_pago > v_total then
    raise exception 'O novo total (R$ %) ficou menor que o já pago (R$ %). Remova um pagamento antes.', v_total, v_pago;
  end if;

  select * into v_ped from public.pedidos where id = v_id;
  return to_jsonb(v_ped);
end $$;

-- Registra um pagamento (e opcionalmente marca como entregue) sem deixar
-- passar do valor que falta.
create or replace function public.receber_pagamento(
  p_id uuid, p_pedido uuid, p_valor numeric, p_forma text, p_taxa numeric,
  p_data date, p_entregar boolean)
returns jsonb language plpgsql security invoker set search_path = ''
as $$
declare
  v_total numeric(10,2);
  v_pago  numeric(10,2);
  v_ped   public.pedidos;
begin
  if not public.eh_membro() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  perform 1 from public.pedidos where id = p_pedido for update;
  if not found then raise exception 'Pedido não encontrado.'; end if;

  if coalesce(p_valor, 0) > 0 and not exists (select 1 from public.pagamentos where id = p_id) then
    select coalesce(sum(qtd * preco), 0) into v_total from public.pedido_itens where pedido_id = p_pedido;
    select coalesce(sum(valor), 0)       into v_pago  from public.pagamentos   where pedido_id = p_pedido;
    if round(p_valor, 2) > v_total - v_pago then
      raise exception 'Valor maior do que falta receber (R$ %).', v_total - v_pago;
    end if;
    insert into public.pagamentos (id, pedido_id, pago_em, valor, forma, taxa)
    values (p_id, p_pedido, coalesce(p_data, public.hoje()), round(p_valor, 2),
            coalesce(nullif(p_forma,''), 'Pix'), round(coalesce(p_taxa, 0), 2));
  end if;

  if p_entregar then
    update public.pedidos set status = 'entregue', entregue_em = coalesce(entregue_em, coalesce(p_data, public.hoje()))
    where id = p_pedido;
  end if;

  select * into v_ped from public.pedidos where id = p_pedido;
  return to_jsonb(v_ped);
end $$;

-- Restaura um backup exportado pelo próprio sistema (só administrador).
-- Junta com o que já existe: registros com o mesmo id são sobrescritos,
-- nada é apagado.
create or replace function public.importar_backup(b jsonb)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare v_max bigint;
begin
  if not public.eh_admin() then raise exception 'Só administrador pode restaurar backup.' using errcode = '42501'; end if;
  if coalesce(b->>'sistema','') <> 'atelie-ponto-a-ponto' then
    raise exception 'Este arquivo não é um backup do Ateliê Ponto a Ponto.';
  end if;

  insert into public.categorias_despesa select * from jsonb_populate_recordset(null::public.categorias_despesa, coalesce(b->'categorias_despesa','[]'))
    on conflict (nome) do update set ordem = excluded.ordem;
  insert into public.servicos select * from jsonb_populate_recordset(null::public.servicos, coalesce(b->'servicos','[]'))
    on conflict (id) do update set nome = excluded.nome, categoria = excluded.categoria, preco = excluded.preco, custo = excluded.custo, ativo = excluded.ativo;
  insert into public.clientes select * from jsonb_populate_recordset(null::public.clientes, coalesce(b->'clientes','[]'))
    on conflict (id) do update set nome = excluded.nome, fone = excluded.fone, obs = excluded.obs;
  insert into public.pedidos (id, numero, cliente_id, recebido_em, entregar_em, status, entregue_em, detalhes, criado_em)
    select id, numero, cliente_id, recebido_em, entregar_em, status, entregue_em, detalhes, coalesce(criado_em, now())
    from jsonb_populate_recordset(null::public.pedidos, coalesce(b->'pedidos','[]'))
    on conflict (id) do update set cliente_id = excluded.cliente_id, recebido_em = excluded.recebido_em, entregar_em = excluded.entregar_em,
      status = excluded.status, entregue_em = excluded.entregue_em, detalhes = excluded.detalhes;
  insert into public.pedido_itens select * from jsonb_populate_recordset(null::public.pedido_itens, coalesce(b->'pedido_itens','[]'))
    on conflict (id) do update set nome = excluded.nome, qtd = excluded.qtd, preco = excluded.preco, custo = excluded.custo, avulso = excluded.avulso, ordem = excluded.ordem;
  insert into public.pagamentos select * from jsonb_populate_recordset(null::public.pagamentos, coalesce(b->'pagamentos','[]'))
    on conflict (id) do update set pago_em = excluded.pago_em, valor = excluded.valor, forma = excluded.forma, taxa = excluded.taxa;
  insert into public.despesas select * from jsonb_populate_recordset(null::public.despesas, coalesce(b->'despesas','[]'))
    on conflict (id) do update set data = excluded.data, descricao = excluded.descricao, categoria = excluded.categoria, valor = excluded.valor;
  insert into public.investimentos select * from jsonb_populate_recordset(null::public.investimentos, coalesce(b->'investimentos','[]'))
    on conflict (id) do update set nome = excluded.nome, data = excluded.data, valor = excluded.valor;
  insert into public.config (chave, valor)
    select chave, valor from jsonb_populate_recordset(null::public.config, coalesce(b->'config','[]'))
    on conflict (chave) do update set valor = excluded.valor, atualizado_em = now();

  select max(numero) into v_max from public.pedidos;
  if v_max is not null then
    perform setval(pg_get_serial_sequence('public.pedidos','numero'), greatest(v_max, 100));
  end if;

  return jsonb_build_object(
    'pedidos',  jsonb_array_length(coalesce(b->'pedidos','[]')),
    'clientes', jsonb_array_length(coalesce(b->'clientes','[]')));
end $$;

-- Lista de usuários para a aba Usuários (só administrador).
create or replace function public.listar_usuarios()
returns table (id uuid, email text, nome text, papel text, ativo boolean, criado_em timestamptz,
               email_confirmado boolean, ultimo_acesso timestamptz)
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.eh_admin() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  return query
    select p.id, p.email, p.nome, p.papel, p.ativo, p.criado_em,
           (u.email_confirmed_at is not null), u.last_sign_in_at
    from public.perfis p
    join auth.users u on u.id = p.id
    order by p.ativo, p.criado_em;
end $$;

-- Confirma o e-mail de uma conta pelo sistema (só administrador).
create or replace function public.confirmar_email(p_id uuid)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not public.eh_admin() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  update auth.users set email_confirmed_at = coalesce(email_confirmed_at, now()) where id = p_id;
  if not found then raise exception 'Usuário não encontrado.'; end if;
end $$;

revoke execute on function public.listar_usuarios() from public, anon;
