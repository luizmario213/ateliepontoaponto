-- ---------- histórico de alterações (auditoria) ----------
create table if not exists public.auditoria (
  id          bigint generated always as identity primary key,
  quando      timestamptz not null default now(),
  usuario     uuid,
  email       text,
  tabela      text not null,
  acao        text not null,
  registro_id text,
  antes       jsonb,
  depois      jsonb
);
create index if not exists auditoria_quando_idx on public.auditoria(quando desc);

create or replace function public.registra_auditoria()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  v_ant jsonb := case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end;
  v_dep jsonb := case when tg_op in ('UPDATE','INSERT') then to_jsonb(new) end;
begin
  if tg_op = 'UPDATE' and (v_ant - 'atualizado_em') = (v_dep - 'atualizado_em') then
    return null; -- nada mudou de verdade
  end if;
  insert into public.auditoria (usuario, email, tabela, acao, registro_id, antes, depois)
  values (auth.uid(),
          (select email from public.perfis where id = auth.uid()),
          tg_table_name, lower(tg_op),
          coalesce(v_dep->>'id', v_ant->>'id', v_dep->>'chave', v_ant->>'chave'),
          v_ant, v_dep);
  return null;
end $$;

