-- ---------- utilidades ----------
create or replace function public.hoje()
returns date language sql stable set search_path = ''
as $$ select (now() at time zone 'America/Fortaleza')::date $$;

create or replace function public.toca_atualizado_em()
returns trigger language plpgsql set search_path = ''
as $$ begin new.atualizado_em := now(); return new; end $$;

-- ---------- perfis (quem pode entrar) ----------
create table if not exists public.perfis (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text not null,
  nome       text not null default '',
  papel      text not null default 'atelie' check (papel in ('atelie','admin')),
  ativo      boolean not null default false,
  criado_em  timestamptz not null default now()
);

-- Toda conta criada em Authentication ganha um perfil DESATIVADO.
-- Só um administrador ativa. Isso protege o sistema mesmo que alguém
-- ligue o cadastro público por engano.
create or replace function public.cria_perfil()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.perfis (id, email, nome)
  values (new.id, coalesce(new.email,''),
          coalesce(nullif(new.raw_user_meta_data->>'nome',''), split_part(coalesce(new.email,''),'@',1)))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists ao_criar_usuario on auth.users;
create trigger ao_criar_usuario after insert on auth.users
  for each row execute function public.cria_perfil();

-- perfis para usuários que já existiam antes deste script
insert into public.perfis (id, email, nome)
select u.id, coalesce(u.email,''), split_part(coalesce(u.email,''),'@',1)
from auth.users u
on conflict (id) do nothing;

create or replace function public.eh_membro()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.perfis where id = auth.uid() and ativo) $$;

create or replace function public.eh_admin()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.perfis where id = auth.uid() and ativo and papel = 'admin') $$;

-- Nunca deixar o sistema sem nenhum administrador ativo.
create or replace function public.protege_ultimo_admin()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if not exists (select 1 from public.perfis where ativo and papel = 'admin') then
    raise exception 'Precisa ficar pelo menos um administrador ativo.' using errcode = 'P0001';
  end if;
  return null;
end $$;

drop trigger if exists ultimo_admin on public.perfis;
create constraint trigger ultimo_admin after update or delete on public.perfis
  deferrable initially deferred
  for each row
  when (old.papel = 'admin' and old.ativo)
  execute function public.protege_ultimo_admin();

-- ---------- catálogo de serviços ----------
create table if not exists public.servicos (
  id            uuid primary key default gen_random_uuid(),
  nome          text not null check (length(btrim(nome)) > 0),
  categoria     text not null default 'Outros',
  preco         numeric(10,2) not null check (preco >= 0),
  custo         numeric(10,2) not null default 0 check (custo >= 0),
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- ---------- clientes ----------
create table if not exists public.clientes (
  id            uuid primary key default gen_random_uuid(),
  nome          text not null check (length(btrim(nome)) > 0),
  fone          text not null default '',
  obs           text not null default '',
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

-- ---------- pedidos ----------
create table if not exists public.pedidos (
  id            uuid primary key default gen_random_uuid(),
  numero        bigint generated by default as identity (start with 101) unique,
  cliente_id    uuid not null references public.clientes(id) on delete restrict,
  recebido_em   date not null default public.hoje(),
  entregar_em   date not null,
  status        text not null default 'recebido'
                check (status in ('recebido','andamento','pronto','entregue')),
  entregue_em   date,
  detalhes      text not null default '',
  criado_por    uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists pedidos_cliente_idx on public.pedidos(cliente_id);
create index if not exists pedidos_recebido_idx on public.pedidos(recebido_em);

create table if not exists public.pedido_itens (
  id         uuid primary key default gen_random_uuid(),
  pedido_id  uuid not null references public.pedidos(id) on delete cascade,
  servico_id uuid references public.servicos(id) on delete set null,
  nome       text not null check (length(btrim(nome)) > 0),
  qtd        integer not null check (qtd > 0),
  preco      numeric(10,2) not null check (preco >= 0),  -- preço cobrado (fica congelado no pedido)
  custo      numeric(10,2) not null default 0 check (custo >= 0), -- custo de material estimado por unidade
  avulso     boolean not null default false,
  ordem      integer not null default 0
);
create index if not exists itens_pedido_idx on public.pedido_itens(pedido_id);

create table if not exists public.pagamentos (
  id         uuid primary key default gen_random_uuid(),
  pedido_id  uuid not null references public.pedidos(id) on delete cascade,
  pago_em    date not null default public.hoje(),
  valor      numeric(10,2) not null check (valor > 0),
  forma      text not null default 'Pix' check (forma in ('Pix','Dinheiro','Débito','Crédito','Outro')),
  taxa       numeric(10,2) not null default 0 check (taxa >= 0),  -- taxa da maquininha, em R$
  criado_em  timestamptz not null default now()
);
create index if not exists pagamentos_pedido_idx on public.pagamentos(pedido_id);
create index if not exists pagamentos_data_idx on public.pagamentos(pago_em);

